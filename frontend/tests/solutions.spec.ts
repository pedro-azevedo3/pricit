import { test, expect } from '@playwright/test';

test('soluções navega para autônomos, calcula serviços e contextualiza o cadastro', async ({ page }, info) => {
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.goto('/');
  const mobile = info.project.name === 'mobile';
  if (mobile) await page.getByRole('button', { name: 'Abrir menu', exact: true }).click();
  const solutions = page.getByRole('button', { name: 'Soluções', exact: true });
  await solutions.click();
  await expect(solutions).toHaveAttribute('aria-expanded', 'true');
  await expect(page.getByRole('link', { name: /^Alimentação/ })).toHaveAttribute('href', '/#como-funciona');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy();
  await page.screenshot({ path: `test-results/solutions-menu-${info.project.name}.png`, animations: 'disabled' });
  await page.keyboard.press('Escape');
  await expect(mobile ? page.getByRole('button', { name: 'Abrir menu', exact: true }) : solutions).toBeFocused();
  if (mobile) await page.getByRole('button', { name: 'Abrir menu', exact: true }).click();
  await solutions.click();
  await page.getByRole('link', { name: /^Profissionais autônomos/ }).click();
  await expect(page).toHaveURL(/\/solucoes\/profissionais-autonomos$/);
  await expect(page).toHaveTitle(/pricit para profissionais autônomos/);
  await expect(page.locator('link[rel="canonical"]')).toHaveAttribute('href', 'https://pricit.up.railway.app/solucoes/profissionais-autonomos');
  await expect(page.getByRole('heading', { level: 1 })).toContainText('Seu tempo é trabalho.');
  if (mobile) await expect(page.getByRole('button', { name: 'Abrir menu', exact: true })).toHaveAttribute('aria-expanded', 'false');
  else await expect(page.getByRole('button', { name: 'Soluções', exact: true })).toHaveAttribute('aria-expanded', 'false');
  await page.locator('img').evaluateAll(imgs => Promise.all(imgs.map(img => { (img as HTMLImageElement).loading = 'eager'; return (img as HTMLImageElement).decode(); })));
  await page.screenshot({ path: `test-results/autonomous-${info.project.name}.png`, fullPage: true, animations: 'disabled' });
  await expect(page.getByTestId('service-price')).toHaveText('R$ 247,00');
  await page.getByLabel('Horas do projeto').fill('2');
  await page.getByLabel('Valor da hora (R$)').fill('50');
  await page.getByLabel('Materiais e despesas (R$)').fill('20');
  await page.getByLabel('Acréscimo sobre o custo (%)').fill('50');
  await expect(page.getByTestId('service-price')).toHaveText('R$ 180,00');
  await page.getByLabel('Horas do projeto').fill('');
  await expect(page.getByTestId('service-price')).toHaveText('—');
  await expect(page.getByRole('alert').filter({ hasText: 'Preencha todos os campos' })).toBeVisible();
  await page.getByLabel('Horas do projeto').fill('0');
  await page.getByLabel('Materiais e despesas (R$)').fill('0');
  await expect(page.getByTestId('service-price')).toHaveText('R$ 0,00');
  await page.getByText('Preciso cadastrar materiais para precificar?', { exact: true }).click();
  await expect(page.getByText('Não. Nos perfis de serviços', { exact: false })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy();
  await page.getByRole('link', { name: 'Precificar meu serviço', exact: true }).click();
  await expect(page).toHaveURL(/\/cadastro\?perfil=freelance$/);
  await expect(page.getByLabel('Tipo de negócio')).toHaveValue('freelance');
  await page.getByLabel('Tipo de negócio').selectOption('creative');
  await expect(page.getByLabel('Tipo de negócio')).toHaveValue('creative');
  await page.goto('/cadastro?perfil=desconhecido');
  await expect(page.getByLabel('Tipo de negócio')).toHaveValue('');
  await page.goto('/cadastro');
  await expect(page.getByLabel('Tipo de negócio')).toHaveValue('');
});

test('menu de soluções fecha ao clicar fora e não transborda em tablet', async ({ page }, info) => {
  await page.setViewportSize({ width: info.project.name === 'mobile' ? 320 : 820, height: 900 });
  await page.goto('/solucoes/profissionais-autonomos');
  if (info.project.name === 'mobile') await page.getByRole('button', { name: 'Abrir menu', exact: true }).click();
  const solutions = page.getByRole('button', { name: 'Soluções', exact: true });
  await solutions.click();
  await expect(page.getByRole('link', { name: /^Profissionais autônomos/ })).toHaveAttribute('aria-current', 'page');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy();
  await page.mouse.click(2, 850);
  if (info.project.name === 'desktop') await expect(solutions).toHaveAttribute('aria-expanded', 'false');
  else await expect(page.getByRole('button', { name: 'Abrir menu', exact: true })).toHaveAttribute('aria-expanded', 'false');
});
