import { test, expect } from '@playwright/test';
test('ingredientes, receita, precificação, histórico, PDF e persistência',async({page,request},testInfo)=>{
 const suffix=`${testInfo.project.name}-${Date.now()}`;
 const ingredientName=`Chocolate ${suffix}`, recipeName=`Brownie ${suffix}`;
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('/app');
 const nav=page.getByRole('navigation',{name:testInfo.project.name==='mobile'?'Navegação móvel':'Navegação principal'});
 await page.getByRole('button',{name:'Novo ingrediente',exact:true}).first().click();
 await expect(page.getByLabel('Unidade de medida')).toHaveValue('g');
 await expect(page.getByLabel('Quantidade da embalagem')).toHaveValue('');
 await page.getByLabel('Quantidade da embalagem').fill('1000');
 await page.getByLabel('Nome do ingrediente').fill(ingredientName);
 await page.getByLabel('Valor pago pela embalagem').fill('40');
 await expect(page.getByRole('dialog')).toContainText('R$ 0,04');
 await page.getByRole('button',{name:'Salvar ingrediente'}).click();
 await expect(page.getByRole('dialog')).toHaveCount(0);
 await page.getByLabel('Pesquisar ingredientes').fill(ingredientName);
 await expect(page.getByRole('row').filter({hasText:ingredientName})).toContainText('R$ 40,00');
 await nav.getByRole('button',{name:'Receitas'}).click();
 await page.getByRole('button',{name:'Nova receita',exact:true}).click();
 await expect(page.getByLabel('Rendimento (unidades)')).toHaveValue('');
 await page.getByLabel('Rendimento (unidades)').fill('12');
 await page.getByLabel('Nome da receita').fill(recipeName);
 await page.getByLabel('Selecionar ingrediente').selectOption((await page.getByLabel('Selecionar ingrediente').locator('option').filter({hasText:ingredientName}).getAttribute('value'))!);
 await expect(page.getByLabel(`Quantidade de ${ingredientName}`,{exact:true})).toHaveCount(0);
 await expect(page.getByRole('button',{name:'Adicionar ingrediente',exact:true})).toBeDisabled();
 await expect(page.getByRole('combobox',{name:'Unidade usada',exact:true})).toHaveValue('g');
 await page.getByLabel('Quantidade usada',{exact:true}).fill('200');
 await page.getByRole('button',{name:'Adicionar ingrediente',exact:true}).click();
 await expect(page.getByRole('button',{name:'Adicionar ingrediente',exact:true})).toBeDisabled();
 await expect(page.getByLabel(`Quantidade de ${ingredientName}`,{exact:true})).toHaveValue('200.00');
 await expect(page.getByLabel('Quantidade usada',{exact:true})).toHaveValue('');
 await page.getByRole('button',{name:`Editar ingrediente ${ingredientName}`,exact:true}).click();
 const ingredientDialog=page.getByRole('dialog',{name:'Editar ingrediente',exact:true});
 await ingredientDialog.getByLabel('Valor pago pela embalagem').fill('80');
 await ingredientDialog.getByRole('button',{name:'Salvar ingrediente',exact:true}).click();
 await expect(ingredientDialog).toHaveCount(0);
 await expect(page.getByLabel('Nome da receita')).toHaveValue(recipeName);
 await expect(page.getByTestId('unit-cost')).toHaveText('R$ 1,33');
 await page.getByRole('button',{name:`Editar ingrediente ${ingredientName}`,exact:true}).click();
 await ingredientDialog.getByLabel('Valor pago pela embalagem').fill('40');
 await ingredientDialog.getByRole('button',{name:'Salvar ingrediente',exact:true}).click();
 await expect(ingredientDialog).toHaveCount(0);

 await page.getByLabel('Custo por embalagem').fill('0.5');
 await page.getByLabel('Despesas operacionais (%)',{exact:true}).fill('10');
 await page.getByLabel('Valor da hora de trabalho').fill('20');
 await page.getByLabel('Preço praticado').fill('8');
 await expect(page.getByTestId('unit-cost')).toHaveText('R$ 3,80');
 await expect(page.getByTestId('suggested-price')).toHaveText('R$ 5,70');
 await page.getByRole('button',{name:'Salvar receita',exact:true}).click();
 await expect(page.getByRole('dialog')).toHaveCount(0);
 await page.reload();
 await nav.getByRole('button',{name:'Receitas'}).click();
 const card=page.locator('article').filter({hasText:recipeName});
 await expect(card).toBeVisible();
 await card.getByRole('button',{name:'Ver e editar receita'}).click();
 await expect(page.getByLabel('Nome da receita')).toHaveValue(recipeName);
 await page.getByLabel('Fechar',{exact:true}).click();
 const pdf=await request.get((await card.getByRole('link',{name:`Exportar ${recipeName} em PDF`}).getAttribute('href'))!);
 expect(pdf.status()).toBe(200);expect((await pdf.body()).subarray(0,5).toString()).toBe('%PDF-');
 await card.getByRole('button',{name:'Precificar vendas'}).click();
 await expect(page.getByLabel('Quantidade de unidades para vender')).toHaveValue('100');
 await expect(page.getByText('R$ 800,00',{exact:true}).first()).toBeVisible();
 await page.getByRole('button',{name:'Salvar precificação',exact:true}).click();
 await expect(page.getByRole('link',{name:'Exportar precificação em PDF',exact:true})).toBeVisible();
 const simulationPdf=await request.get((await page.getByRole('link',{name:'Exportar precificação em PDF',exact:true}).getAttribute('href'))!);
 expect(simulationPdf.status()).toBe(200);
 await nav.getByRole('button',{name:'Ingredientes'}).click();
 await page.getByLabel(`Editar ${ingredientName}`,{exact:true}).click();
 await page.getByLabel('Valor pago pela embalagem').fill('80');
 await page.getByRole('button',{name:'Salvar ingrediente'}).click();
 await expect(page.getByRole('dialog')).toHaveCount(0);
 await nav.getByRole('button',{name:'Receitas'}).click();
 await expect(page.locator('article').filter({hasText:recipeName})).toContainText('R$ 4,52');
 await nav.getByRole('button',{name:/^Precificação/}).click();
 await page.getByRole('button',{name:`Ver precificação de ${recipeName}`,exact:true}).click();
 await expect(page.getByRole('dialog')).toContainText('R$ 3,80');
 await page.getByLabel('Fechar',{exact:true}).click();
 await nav.getByRole('button',{name:'Ingredientes'}).click();
 await page.getByLabel(`Excluir ${ingredientName}`,{exact:true}).click();
 await page.getByRole('button',{name:'Confirmar',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Arquivar ingrediente?'})).toBeVisible();
 await page.getByRole('button',{name:'Confirmar',exact:true}).click();
 await expect(page.getByRole('dialog')).toHaveCount(0);
 await page.getByLabel('Mostrar arquivados').check();
 await page.getByLabel('Pesquisar ingredientes').fill(ingredientName);
 await expect(page.getByRole('row').filter({hasText:ingredientName})).toContainText('Arquivado');
 await nav.getByRole('button',{name:'Receitas'}).click();
 await page.getByLabel(`Excluir ${recipeName}`,{exact:true}).click();
 await page.getByRole('button',{name:'Confirmar',exact:true}).click();
 await expect(page.getByRole('dialog')).toHaveCount(0);
 await nav.getByRole('button',{name:/^Precificação/}).click();
 await page.getByRole('button',{name:`Ver precificação de ${recipeName}`,exact:true}).click();
 await expect(page.getByRole('dialog')).toContainText('R$ 800,00');
 await page.getByLabel('Fechar',{exact:true}).click();
 await page.screenshot({path:`test-results/${testInfo.project.name}-simulator.png`,fullPage:true});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBeTruthy();
 expect(errors).toEqual([]);
 const ingredients=await (await request.get('/api/v1/ingredients?include_archived=true')).json();
 const owned=ingredients.find((i:{name:string})=>i.name===ingredientName);
 if(owned)await request.delete('/api/v1/ingredients/'+owned.id);
});
